#!/usr/bin/env python3
"""Download the overlay fonts (SIL Open Font License, from Google Fonts) into
ui/static/assets/fonts/overlay: Latin and Latin Extended subsets of weights 400-700,
a fonts.css with their @font-face rules, and each font's licence. Uses curl, so the
system proxy settings apply. Run from the repository root:  python3 tools/fetch-overlay-fonts.py
"""
import hashlib, os, re, subprocess, sys

# Family name -> folder in github.com/google/fonts/tree/main/ofl (for the licence).
FONTS = {
    'Barlow Condensed': 'barlowcondensed', 'Rajdhani': 'rajdhani', 'Oswald': 'oswald',
    'Titillium Web': 'titilliumweb', 'Chakra Petch': 'chakrapetch', 'Saira Semi Condensed': 'sairasemicondensed',
    'Roboto Condensed': 'robotocondensed', 'Exo 2': 'exo2', 'Inter': 'inter', 'Montserrat': 'montserrat',
    'Teko': 'teko', 'Kanit': 'kanit', 'Orbitron': 'orbitron', 'Sora': 'sora', 'Space Grotesk': 'spacegrotesk',
    'Archivo Narrow': 'archivonarrow', 'Big Shoulders Display': 'bigshouldersdisplay',
    'IBM Plex Sans Condensed': 'ibmplexsanscondensed', 'Fira Sans Condensed': 'firasanscondensed', 'Antonio': 'antonio',
}
WEIGHTS = [400, 500, 600, 700]
SUBSETS = ('latin', 'latin-ext')
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'
OUT = 'ui/static/assets/fonts/overlay'


def get(url, binary=False):
    r = subprocess.run(['curl', '-sSfL', '-A', UA, url], capture_output=True)
    if r.returncode != 0:
        return None
    return r.stdout if binary else r.stdout.decode('utf-8')


def slug(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def main():
    os.makedirs(f'{OUT}/licenses', exist_ok=True)
    css = ['/* Overlay fonts (SIL Open Font License 1.1, see licenses/). Generated by tools/fetch-overlay-fonts.py. */']
    for family, ofl in FONTS.items():
        faces = 0
        seen = set()
        for w in WEIGHTS:
            text = get(f"https://fonts.googleapis.com/css2?family={family.replace(' ', '+')}:wght@{w}&display=swap")
            if not text:
                continue  # this weight does not exist for the family
            for subset, block in re.findall(r'/\* ([a-z-]+) \*/\s*(@font-face \{.*?\})', text, re.S):
                if subset not in SUBSETS:
                    continue
                url = re.search(r'url\((https://[^)]+\.woff2)\)', block).group(1)
                name = f"{slug(family)}-{w}-{subset}-{hashlib.md5(url.encode()).hexdigest()[:6]}.woff2"
                if url in seen:
                    # A variable font serves every weight from one file: reuse it.
                    name = seen_names[url]
                else:
                    data = get(url, binary=True)
                    if not data:
                        sys.exit(f'download failed: {url}')
                    with open(f'{OUT}/{name}', 'wb') as f:
                        f.write(data)
                    seen.add(url)
                    seen_names[url] = name
                rng = re.search(r'unicode-range: ([^;]+);', block).group(1)
                css.append(f"@font-face {{ font-family: '{family}'; font-weight: {w}; font-display: swap; src: url('/assets/fonts/overlay/{name}') format('woff2'); unicode-range: {rng}; }}")
                faces += 1
        lic = get(f'https://raw.githubusercontent.com/google/fonts/main/ofl/{ofl}/OFL.txt')
        if not lic:
            sys.exit(f'no licence for {family}')
        with open(f'{OUT}/licenses/{slug(family)}-OFL.txt', 'w') as f:
            f.write(lic)
        print(f'{family}: {faces} faces')
    with open(f'{OUT}/fonts.css', 'w') as f:
        f.write('\n'.join(css) + '\n')


seen_names = {}
if __name__ == '__main__':
    main()
